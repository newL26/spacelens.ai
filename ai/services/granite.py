"""
IBM watsonx.ai Granite LLM client.

Sends satellite image predictions to the Granite model and returns
a structured intelligence report in plain text.
"""
import logging

from django.conf import settings

logger = logging.getLogger(__name__)


class GraniteService:
    """
    Thin client for the IBM watsonx.ai text-generation API.

    Configuration (all read from Django settings / .env):
        WATSONX_API_KEY    — IBM Cloud API key
        WATSONX_PROJECT_ID — watsonx.ai project ID
        WATSONX_URL        — regional endpoint (default: us-south)
        WATSONX_MODEL_ID   — model identifier (default: ibm/granite-4-h-small)
    """

    # ── Generation hyperparameters ────────────────────────────────────────────
    _PARAMS = {
        "decoding_method": "greedy",
        "max_new_tokens": 900,
        "min_new_tokens": 120,
        "stop_sequences": [],
        "repetition_penalty": 1.1,
        "temperature": 0.7,
    }

    def __init__(self) -> None:
        self._api_key: str    = getattr(settings, "WATSONX_API_KEY",    "")
        self._project_id: str = getattr(settings, "WATSONX_PROJECT_ID", "")
        self._url: str        = getattr(settings, "WATSONX_URL",        "https://us-south.ml.cloud.ibm.com")
        self._model_id: str   = getattr(settings, "WATSONX_MODEL_ID",   "ibm/granite-4-h-small")
        self._client          = None
        self._fallback_reason = "unknown"

        logger.info(
            "Granite config status — api_key_set=%s project_id_set=%s url=%s model=%s",
            bool(self._api_key),
            bool(self._project_id),
            self._url,
            self._model_id,
        )

        if self._api_key and self._project_id:
            self._client = self._build_client()
            if self._client is None:
                self._fallback_reason = "client_initialization_failed"
        else:
            self._fallback_reason = "missing_configuration"
            logger.warning(
                "WATSONX_API_KEY or WATSONX_PROJECT_ID not set. "
                "Granite responses will be replaced with a placeholder."
            )

    # ── Client construction ───────────────────────────────────────────────────
    def _build_client(self):
        """Instantiate the ibm-watsonx-ai text model client."""
        try:
            from ibm_watsonx_ai import Credentials
            from ibm_watsonx_ai.foundation_models import Model
            from ibm_watsonx_ai.metanames import GenTextParamsMetaNames as GenParams

            credentials = Credentials(url=self._url, api_key=self._api_key)

            model = Model(
                model_id=self._model_id,
                credentials=credentials,
                project_id=self._project_id,
                params={
                    GenParams.DECODING_METHOD:   self._PARAMS["decoding_method"],
                    GenParams.MAX_NEW_TOKENS:    self._PARAMS["max_new_tokens"],
                    GenParams.MIN_NEW_TOKENS:    self._PARAMS["min_new_tokens"],
                    GenParams.STOP_SEQUENCES:    self._PARAMS["stop_sequences"],
                    GenParams.REPETITION_PENALTY: self._PARAMS["repetition_penalty"],
                    GenParams.TEMPERATURE:       self._PARAMS["temperature"],
                },
            )
            logger.info("Granite client initialised — model: %s", self._model_id)
            return model

        except ImportError as exc:
            self._fallback_reason = "missing_dependency"
            logger.error(
                "ibm-watsonx-ai package not installed. "
                "Run: pip install ibm-watsonx-ai  (%s)", exc
            )
            return None
        except Exception as exc:
            self._fallback_reason = f"client_initialization_failed: {type(exc).__name__}"
            logger.exception("Failed to initialise Granite client: %s", exc)
            return None

    # ── Public API ────────────────────────────────────────────────────────────
    def explain_prediction(
        self,
        top3: list[tuple[str, float]],
    ) -> str:
        """
        Generate an environmental intelligence report for the given predictions.

        Args:
            top3: List of (class_name, confidence_pct) tuples, highest first.
                  Example: [("Forest", 94.7), ("River", 3.1), ("Pasture", 1.2)]

        Returns:
            Plain-text report generated by Granite, or a fallback string on error.
        """
        if self._client is None:
            return self._fallback_response(top3, reason=self._fallback_reason)

        prompt = _build_prompt(top3)
        logger.debug("Granite prompt:\n%s", prompt)

        try:
            response = self._client.generate_text(prompt=prompt)
            text = response.strip() if isinstance(response, str) else str(response).strip()

            if not text:
                logger.warning("Granite returned empty response.")
                return self._fallback_response(top3, reason="empty_response")

            logger.info(
                "Granite response received (%d chars) for top class: %s",
                len(text),
                top3[0][0] if top3 else "N/A",
            )
            return text

        except Exception as exc:
            logger.exception("Granite API call failed: %s", exc)
            return self._fallback_response(top3, reason=f"generation_error: {type(exc).__name__}")

    # ── Fallback ──────────────────────────────────────────────────────────────
    @staticmethod
    def _fallback_response(top3: list[tuple[str, float]], reason: str = "unknown") -> str:
        """
        Return a structured placeholder when Granite is unavailable.
        Preserves the report structure so the UI renders correctly.
        """
        top_class = top3[0][0] if top3 else "Unknown"
        top_conf  = top3[0][1] if top3 else 0.0

        reason_key = (reason or "unknown").split(":", 1)[0].strip().lower()
        reason_messages = {
            "missing_configuration": (
                "Risk assessment requires IBM watsonx.ai configuration. "
                "Please set WATSONX_API_KEY and WATSONX_PROJECT_ID in your .env file."
            ),
            "missing_dependency": (
                "Risk assessment is unavailable because ibm-watsonx-ai is not installed "
                "in this runtime environment."
            ),
            "client_initialization_failed": (
                "Risk assessment is unavailable because the Granite client failed to "
                "initialize with the current credentials or endpoint settings."
            ),
            "generation_error": (
                "Risk assessment is unavailable because the Granite API request failed "
                "during text generation."
            ),
            "empty_response": (
                "Risk assessment is unavailable because Granite returned an empty "
                "response for this request."
            ),
            "unknown": (
                "Risk assessment is currently unavailable due to an unknown Granite "
                "service issue."
            ),
        }
        risk_message = reason_messages.get(reason_key, reason_messages["unknown"])

        lines = [
            f"SATELLITE IMAGE ANALYSIS — {top_class.upper()}",
            "",
            "1. AREA COMPOSITION",
            f"The deep learning model detected {top_class} as the dominant land-cover type "
            f"with {top_conf:.1f}% confidence. "
            + (
                f"Secondary candidates include {top3[1][0]} ({top3[1][1]:.1f}%) "
                f"and {top3[2][0]} ({top3[2][1]:.1f}%)."
                if len(top3) >= 3 else ""
            ),
            "",
            "2. ENVIRONMENTAL SIGNIFICANCE",
            "This land-cover type plays an important role in the local ecosystem. "
            "Detailed analysis requires IBM Granite credentials to be configured.",
            "",
            "3. HUMAN ACTIVITIES",
            "Analysis of human land-use patterns in this area is pending Granite integration.",
            "",
            "4. RISKS & OBSERVATIONS",
            risk_message,
            "",
            "5. SUMMARY",
            f"The satellite image has been successfully classified as {top_class} "
            f"with {top_conf:.1f}% confidence by the TensorFlow model. "
            "Connect IBM Granite to receive a full AI-generated intelligence report.",
            "",
            "─" * 60,
            "NOTE: This is a placeholder response. "
            f"Granite fallback reason: {reason or 'unknown'}.",
        ]
        return "\n".join(lines)


# ── Prompt builder (module-level function) ────────────────────────────────────
def _build_prompt(top3: list[tuple[str, float]]) -> str:
    """
    Construct the structured Granite instruction prompt.

    The prompt follows the <<SYS>> / [INST] format understood by
    Granite instruct models.

    Args:
        top3: List of (class_name, confidence_pct) tuples, highest first.

    Returns:
        Fully formatted prompt string ready for generate_text().
    """
    # Format the prediction block
    pred_block = "\n".join(
        f"  - {cls}: {prob:.1f}%"
        for cls, prob in top3
    )
    top_class = top3[0][0] if top3 else "Unknown"

    prompt = f"""<<SYS>>
You are an expert satellite imagery analyst and environmental scientist.
You provide structured, precise, and insightful reports based on AI-classified satellite imagery.
Write in clear professional English. Use numbered sections exactly as instructed.
<</SYS>>

[INST]
A deep learning model has analysed a satellite image and produced the following land-cover predictions:

{pred_block}

Based on these predictions, generate a structured Environmental Intelligence Report with EXACTLY these 5 sections:

1. AREA COMPOSITION
   Describe what the dominant land cover ({top_class}) indicates about this area's physical composition,
   terrain characteristics, vegetation density, and how the secondary classes relate to it.

2. ENVIRONMENTAL SIGNIFICANCE
   Explain the ecological and environmental importance of this land-cover type.
   Include biodiversity, carbon sequestration, water cycle role, and climate relevance.

3. HUMAN ACTIVITIES
   Describe likely human activities, land-use patterns, economic activities,
   and infrastructure visible or implied in this type of terrain.

4. RISKS & OBSERVATIONS
   Identify environmental risks such as deforestation, urban sprawl, flood risk,
   soil erosion, pollution potential, or climate vulnerability for this land-cover type.

5. SUMMARY
   Provide a concise 2–3 sentence summary of the overall intelligence assessment,
   the confidence level, and the most important takeaway for a decision-maker.

Write each section clearly and concisely. Do not add any other sections or preamble.
[/INST]"""

    return prompt
